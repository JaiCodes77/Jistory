TOKEN_RE = re.compile(r"[A-Za-z][A-Za-z0-9_+-]{2,}")


def extract_terms(text: str | None) -> dict[str, str]:
    """Map lowercase term → display form (first casing seen)."""
    found: dict[str, str] = {}
    for token in TOKEN_RE.findall(text or ""):
        lowered = token.lower()
        if lowered in STOPWORDS:
            continue
        if len(lowered) <= 3 and not token.isupper():
            continue
        found.setdefault(lowered, token)
    return found


def shared_display(left: dict[str, str], right: dict[str, str], *, limit: int = 2) -> list[str]:
    keys = sorted(set(left) & set(right), key=lambda key: (-len(key), key))
    labels: list[str] = []
    for key in keys[:limit]:
        labels.append(left.get(key) or right.get(key) or key)
    return labels
